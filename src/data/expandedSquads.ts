import type { Player, PlayerStats, Position, Squad } from '../types/game';

type DemoPlayerSeed = Omit<Player, 'id' | 'countryCode' | 'worldCupYear' | 'eraGroup' | 'stats' | 'traits'> & {
  traits?: string[];
};

const slug = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const stat = (value: number) => Math.max(1, Math.min(99, Math.round(value)));

const roleGroupFor = (position: Position) => {
  if (position === 'GK') return 'goalkeeper';
  if (['LB', 'CB', 'RB', 'LWB', 'RWB'].includes(position)) return 'defense';
  if (['DM', 'CM', 'AM', 'LM', 'RM'].includes(position)) return 'midfield';
  return 'attack';
};

const statsFor = (position: Position, rating: number): PlayerStats => {
  const group = roleGroupFor(position);

  if (group === 'goalkeeper') {
    return {
      pace: stat(rating - 42),
      shooting: stat(rating - 62),
      passing: stat(rating - 16),
      defense: stat(rating + 3),
      physical: stat(rating - 7),
      technique: stat(rating - 14),
    };
  }

  if (group === 'defense') {
    return {
      pace: stat(rating - 4),
      shooting: stat(rating - 26),
      passing: stat(rating - 8),
      defense: stat(rating + 5),
      physical: stat(rating + 2),
      technique: stat(rating - 7),
    };
  }

  if (group === 'midfield') {
    return {
      pace: stat(rating - 8),
      shooting: stat(rating - 10),
      passing: stat(rating + 4),
      defense: stat(rating - 3),
      physical: stat(rating - 2),
      technique: stat(rating + 3),
    };
  }

  return {
    pace: stat(rating + 1),
    shooting: stat(rating + 4),
    passing: stat(rating - 2),
    defense: stat(rating - 25),
    physical: stat(rating - 3),
    technique: stat(rating + 3),
  };
};

const defaultTraits = (position: Position) => {
  const group = roleGroupFor(position);
  if (group === 'goalkeeper') return ['Shot stopping', 'Fast release'];
  if (group === 'defense') return ['Tight marking', 'Aerial duels'];
  if (group === 'midfield') return ['Tempo control', 'Press resistance'];
  return ['Final-third threat', 'Sharp movement'];
};

const p = (
  shirtNumber: number,
  name: string,
  positions: Position[],
  role: string,
  club: string,
  rating: number,
  options: Partial<Pick<Player, 'isLegend' | 'ballonDorWinner' | 'traits'>> = {},
): DemoPlayerSeed => ({
  shirtNumber,
  name,
  positions,
  role,
  club,
  rating,
  isLegend: options.isLegend,
  ballonDorWinner: options.ballonDorWinner,
  traits: options.traits,
});

const squad = (
  config: Omit<Squad, 'id' | 'players' | 'flag'> & { eraGroup: string; players: DemoPlayerSeed[] },
): Squad => ({
  id: `${config.countryCode.toLowerCase()}-${config.year}`,
  countryCode: config.countryCode,
  country: config.country,
  flag: config.countryCode,
  year: config.year,
  editionName: config.editionName,
  finish: config.finish,
  manager: config.manager,
  style: config.style,
  baseStrength: config.baseStrength,
  players: config.players.map((player) => ({
    ...player,
    id: `${config.countryCode.toLowerCase()}-${config.year}-${slug(player.name)}`,
    countryCode: config.countryCode,
    worldCupYear: config.year,
    eraGroup: config.eraGroup,
    stats: statsFor(player.positions[0], player.rating),
    traits: player.traits ?? defaultTraits(player.positions[0]),
  })),
});

